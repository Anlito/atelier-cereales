const fs=require('fs'),path=require('path'),assert=require('assert/strict');
process.chdir(path.join(__dirname,'..'));
fs.mkdirSync('.cache/recette',{recursive:true});
const puppeteer=require('puppeteer-core');
(async()=>{
  const b=await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,userDataDir:path.resolve('.cache/recette/browser-profile'),args:['--no-sandbox','--disable-gpu'],timeout:20000});
  try{
    const contexte=await b.createBrowserContext();
    const p=await contexte.newPage(),errors=[],requests=[];p.on('pageerror',e=>errors.push(e.message));p.on('request',r=>requests.push(r.url()));
    await p.goto('file:///'+path.resolve('site/index.html').replaceAll('\\','/')+'?enseignant=1',{waitUntil:'networkidle0',timeout:40000});
    await p.waitForFunction(()=>window.Atelier?.programmation,{timeout:20000});
    assert(requests.some(u=>u.startsWith('https://anlito.github.io/labo-blocs/module/labo-blocs-noyau.js')));
    assert(!requests.some(u=>u.includes('/atelier-cereales/site/vendor/')));
    assert.deepEqual(errors,[]);
    await p.screenshot({path:'.cache/recette/programmation.png',fullPage:true});
    console.log('OK programmation : moteur en ligne, éditeur monté, aucune copie locale, aucune erreur.');
    const prof=await contexte.newPage();prof.on('pageerror',e=>errors.push(e.message));
    await prof.goto('file:///'+path.resolve('site/prof.html').replaceAll('\\','/'),{waitUntil:'networkidle0',timeout:40000});
    await prof.waitForFunction(()=>document.querySelector('.prof-exercices-version').textContent.includes('en ligne'));
    assert.deepEqual(errors,[]);console.log('OK professeur : version centrale affichée sans erreur.');
    await p.goto('file:///'+path.resolve('site/index.html').replaceAll('\\','/'),{waitUntil:'networkidle0',timeout:40000});
    console.log('Contrôle saisie : accueil élève chargé.');
    await p.evaluate(()=>{
      const A=Atelier,d=A.creerProgression({eleves:['Test'],classe:'5A'});
      window.sessionTest=A.creerSession({donnees:d});document.querySelector('.ecran-accueil').hidden=true;A.demarrerProjet(sessionTest);
    });
    console.log('Contrôle saisie : équipe créée.');
    await p.$eval('[data-onglet="objet"]',el=>el.click());console.log('Objet ouvert.');await p.$eval('[data-verifier="classement"]',el=>el.click());console.log('Classement vérifié.');
    await p.$eval('[data-onglet="problematique"]',el=>el.click());console.log('Problématique ouverte.');
    await p.$eval('.champ-definition',(el,value)=>{el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}));},'Un objet technique répond à un besoin humain.');console.log('Définition saisie.');
    await p.$eval('[data-idee="0"]',(el,value)=>{el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}));},'Un distributeur automatique');
    await p.$eval('[data-onglet="dessins"]',el=>el.click());
    assert.equal((await p.$$('[data-dessin]')).length,16);
    await p.$eval('[data-dessin="croquis"]',el=>el.click());
    const fixture=path.resolve('.cache/recette/equipe.json');
    fs.writeFileSync(fixture,await p.evaluate(()=>JSON.stringify(sessionTest.donnees)));
    await (await prof.$('.entree-fichiers')).uploadFile(fixture);
    await prof.waitForSelector('.ligne-equipe');await prof.$eval('.ligne-equipe',el=>el.click());await prof.$eval('[data-onglet="carnet"]',el=>el.click());
    assert((await prof.$eval('.pe-contenu',e=>e.textContent)).includes('Un objet technique répond à un besoin humain.'));
    await prof.$eval('.btn-reglages',el=>el.click());await prof.$eval('[data-noter-carnet="croquis"]',el=>el.click());await prof.$eval('.btn-fermer-reglages',el=>el.click());
    await prof.select('[data-note-manuelle="croquis"]','3');
    assert.equal(await prof.$eval('[data-note-manuelle="croquis"]',e=>e.value),'3');
    assert.deepEqual(errors,[]);console.log('OK carnet : définition après Vérifier, 16 critères, lecture professeur et niveau manuel.');
    const absent=await contexte.newPage();await absent.setRequestInterception(true);
    absent.on('request',r=>r.url().startsWith('https://anlito.github.io/labo-blocs/')?r.abort():r.continue());
    await absent.goto('file:///'+path.resolve('site/index.html').replaceAll('\\','/'),{waitUntil:'networkidle0'});
    await absent.waitForFunction(()=>[...document.querySelectorAll('[role="alert"]')].some(e=>e.textContent.includes('connexion à Labo Blocs')));
    assert.equal(await absent.evaluate(()=>window.Atelier?.sessionCourante),undefined);
    console.log('OK réseau absent : message et bouton Réessayer, aucune session ou sauvegarde modifiée.');
  }finally{await b.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
